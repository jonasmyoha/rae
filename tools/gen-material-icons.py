#!/usr/bin/env python3
"""Generate lib/ui/IconCodepoints.rae and bake the Material Icons atlas.

Both come from the font's own codepoints file,
lib/assets/fonts/MaterialIconsRound-Regular.codepoints (one "name hex" line
per icon, published beside the font by google/material-design-icons), so the
name table and the atlas hold the same full set.

  python3 tools/gen-material-icons.py          # write IconCodepoints.rae
  python3 tools/gen-material-icons.py --bake   # and bake the atlas

The table: one String const per first character, each a run of fixed-width
records (the name padded with spaces, then 4 hex digits) sorted by name, so
iconCodepoint finds a name by a binary search in its group.

The atlas: every codepoint at 40 px per em, distance range 10 (the 4:1 ratio
of the old 48/12 atlas), packed into 2048x2048, written as the .mtsdf.png that
SdfText.loadSdfFontJson reads. 48 px would need 4096x4096 (64 MB of GPU
memory); 2048x2048 is 16 MB. Requires msdf-atlas-gen.
"""
import os
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fonts = os.path.join(root, "lib", "assets", "fonts")
stem = os.path.join(fonts, "MaterialIconsRound-Regular")
codepointsPath = stem + ".codepoints"
outPath = os.path.join(root, "lib", "ui", "IconCodepoints.rae")


def readCodepoints():
    entries = {}
    with open(codepointsPath) as source:
        for line in source:
            parts = line.split()
            if len(parts) != 2:
                continue
            name, code = parts
            if len(code) != 4:
                sys.exit(f"{name}: codepoint {code} is not 4 hex digits")
            entries[name] = code.lower()
    return entries


def groupName(first):
    if first.isdigit():
        return f"iconsDigit{first}"
    return f"icons{first.upper()}"


def generate(entries):
    groups = {}
    for name in sorted(entries):
        groups.setdefault(name[0], []).append(name)
    out = []
    out.append("# Material Icons (Round): the codepoint of each icon name, GENERATED by")
    out.append("# tools/gen-material-icons.py from lib/assets/fonts/")
    out.append("# MaterialIconsRound-Regular.codepoints (the font's own list, Apache 2.0).")
    out.append("# Do not edit; rerun the tool. The baked atlas beside the font")
    out.append("# (MaterialIconsRound-Regular.mtsdf.json/.png) holds every one of them.")
    out.append("#")
    out.append("# The renderer draws a `mat:<name>` Sprite as the glyph iconText returns;")
    out.append("# the scene loader reports a name iconCodepoint does not know as an")
    out.append("# `unknownIcon` diagnostic (ui/IconCheck), so it never silently draws")
    out.append("# nothing. The codepoints are the same in every Material Icons style.")
    out.append("#")
    out.append("# Each group is one const per first character: fixed-width records, the")
    out.append("# name padded with spaces to the group's width less 4, then 4 hex digits,")
    out.append("# sorted by name, so a lookup is a binary search inside its group.")
    out.append(f"# {len(entries)} names.")
    out.append("")
    out.append("# The codepoint of the icon `name`, or -1 for a name the font does not have")
    out.append("func iconCodepoint(name: view String) ret Int {")
    out.append("  let first: Int = name.byteAt(index: 0)")
    for first in sorted(groups):
        names = groups[first]
        width = max(len(name) for name in names) + 1 + 4
        out.append(f"  if first is {ord(first)} {{")
        out.append(f"    ret iconSearch(name: name, table: {groupName(first)}, width: {width})")
        out.append("  }")
    out.append("  ret -1")
    out.append("}")
    out.append("")
    out.append("# Whether the font has an icon called `name`")
    out.append("func isIconName(name: view String) ret Bool {")
    out.append("  ret iconCodepoint(name: name) >= 0")
    out.append("}")
    out.append("")
    out.append("# The UTF-8 text of the icon `name` (one character), or \"\" for a name the")
    out.append("# font does not have (the loader reports such a name at load)")
    out.append("func iconText(name: view String) ret String {")
    out.append("  let code: Int = iconCodepoint(name: name)")
    out.append("  if code < 0 {")
    out.append("    ret \"\"")
    out.append("  }")
    out.append("  ret String.fromCodepoint(code: code)")
    out.append("}")
    out.append("")
    out.append("# A binary search of `table`'s records of `width` bytes for `name`: its")
    out.append("# codepoint, or -1")
    out.append("func iconSearch(name: view String, table: view String, width: view Int) ret Int {")
    out.append("  let nameLength: Int = name.length()")
    out.append("  if nameLength is 0 or nameLength > width - 5 {")
    out.append("    ret -1")
    out.append("  }")
    out.append("  var low: Int = 0")
    out.append("  var high: Int = table.length() / width - 1")
    out.append("  loop low <= high {")
    out.append("    let middle: Int = (low + high) / 2")
    out.append("    let order: Int = iconCompare(name: name, table: table, start: middle * width)")
    out.append("    if order is 0 {")
    out.append("      ret iconHex(table: table, start: middle * width + width - 4)")
    out.append("    }")
    out.append("    if order < 0 {")
    out.append("      high = middle - 1")
    out.append("    } else {")
    out.append("      low = middle + 1")
    out.append("    }")
    out.append("  }")
    out.append("  ret -1")
    out.append("}")
    out.append("")
    out.append("# `name` against the record at `start`: < 0, 0 or > 0. The padding is a")
    out.append("# space, which sorts before every character of a name, so a name that is")
    out.append("# a prefix of the record's comes first")
    out.append("func iconCompare(name: view String, table: view String, start: view Int) ret Int {")
    out.append("  let nameLength: Int = name.length()")
    out.append("  loop var i: Int = 0, i < nameLength, ++i {")
    out.append("    let difference: Int = name.byteAt(index: i) - table.byteAt(index: start + i)")
    out.append("    if difference is not 0 {")
    out.append("      ret difference")
    out.append("    }")
    out.append("  }")
    out.append("  if table.byteAt(index: start + nameLength) is 32 {")
    out.append("    ret 0")
    out.append("  }")
    out.append("  ret -1")
    out.append("}")
    out.append("")
    out.append("# The 4 hex digits at `start` as a number")
    out.append("func iconHex(table: view String, start: view Int) ret Int {")
    out.append("  var value: Int = 0")
    out.append("  loop var i: Int = 0, i < 4, ++i {")
    out.append("    let digit: Int = table.byteAt(index: start + i)")
    out.append("    if digit >= 97 {")
    out.append("      value = value * 16 + digit - 87")
    out.append("    } else {")
    out.append("      value = value * 16 + digit - 48")
    out.append("    }")
    out.append("  }")
    out.append("  ret value")
    out.append("}")
    for first in sorted(groups):
        names = groups[first]
        width = max(len(name) for name in names) + 1 + 4
        records = "".join(name.ljust(width - 4) + entries[name] for name in names)
        out.append("")
        out.append(f"const {groupName(first)}: String = \"{records}\"")
    out.append("")
    with open(outPath, "w") as target:
        target.write("\n".join(out))
    print(f"wrote {os.path.relpath(outPath, root)}: {len(entries)} names in {len(groups)} groups")


def bake(entries):
    generator = os.environ.get("MSDF_ATLAS_GEN", "msdf-atlas-gen")
    codes = sorted(set(entries.values()))
    charset = stem + ".charset.txt"
    with open(charset, "w") as target:
        target.write(",".join("0x" + code for code in codes))
    try:
        subprocess.run([
            generator, "-font", stem + ".otf", "-charset", charset,
            "-type", "mtsdf", "-format", "png",
            "-imageout", stem + ".mtsdf.png", "-json", stem + ".mtsdf.json",
            "-size", "40", "-pxrange", "10", "-dimensions", "2048", "2048",
            "-yorigin", "bottom",
        ], check=True)
    finally:
        os.remove(charset)
    print(f"baked {len(codes)} glyphs into {os.path.relpath(stem, root)}.mtsdf.{{json,png}}")


entries = readCodepoints()
generate(entries)
if "--bake" in sys.argv[1:]:
    bake(entries)
